document.documentElement.classList.add("motion-ready");

const languageButtons = document.querySelectorAll(".lang-btn");
const menuToggle = document.querySelector(".menu-toggle");
const navMenu = document.querySelector("#navMenu");
const form = document.querySelector("#proposalForm");
const formMessage = document.querySelector("#formMessage");
const modal = document.querySelector("#policyModal");
const modalDialog = modal ? modal.querySelector(".modal-dialog") : null;
const modalTitle = document.querySelector("#modalTitle");
const modalBody = document.querySelector("#modalBody");
const siteHeader = document.querySelector("#siteHeader");
const heroMedia = document.querySelector(".hero-media");
const storyLayers = document.querySelectorAll(".story-layer");
const storySteps = document.querySelectorAll(".story-step");
const sections = document.querySelectorAll(".section, .storytelling-section");
let activeLanguage = "en";
let ticking = false;

document.body.classList.add("is-loaded");

function setLanguage(language) {
  activeLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key]) {
      element.textContent = translations[language][key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (formMessage && formMessage.textContent.trim()) {
    formMessage.textContent = translations[language].formThanks;
  }
}

function closeMobileMenu() {
  if (!navMenu || !menuToggle) return;
  navMenu.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

if (menuToggle && navMenu) {
  menuToggle.addEventListener("click", () => {
    const isOpen = navMenu.classList.toggle("open");
    menuToggle.setAttribute("aria-expanded", String(isOpen));
  });
}

document.querySelectorAll(".nav-links a, .nav-tools a").forEach((link) => {
  link.addEventListener("click", closeMobileMenu);
});

if (form && formMessage) {
  form.addEventListener("submit", (event) => {
    event.preventDefault();
    formMessage.textContent = translations[activeLanguage].formThanks;
    form.reset();
  });
}

function openModal(type) {
  if (!modal || !modalDialog || !modalTitle || !modalBody) return;
  const titleKey = type === "terms" ? "termsTitle" : "privacyTitle";
  const bodyKey = type === "terms" ? "termsBody" : "privacyBody";
  modalTitle.textContent = translations[activeLanguage][titleKey];
  modalBody.innerHTML = translations[activeLanguage][bodyKey];
  modal.classList.add("active");
  modal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
  modalDialog.focus();
}

function closeModal() {
  if (!modal) return;
  modal.classList.remove("active");
  modal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
}

document.querySelectorAll("[data-modal]").forEach((button) => {
  button.addEventListener("click", () => openModal(button.dataset.modal));
});

document.querySelectorAll("[data-close-modal]").forEach((element) => {
  element.addEventListener("click", closeModal);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && modal && modal.classList.contains("active")) {
    closeModal();
  }
});

const revealElements = document.querySelectorAll(".reveal");

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  revealElements.forEach((element) => observer.observe(element));

  const sectionObserver = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      entry.target.classList.toggle("is-active", entry.isIntersecting);
    });
  }, { threshold: 0.18 });

  sections.forEach((section) => sectionObserver.observe(section));
} else {
  revealElements.forEach((element) => element.classList.add("visible"));
  sections.forEach((section) => section.classList.add("is-active"));
}

function setStoryStep(index) {
  storyLayers.forEach((layer, layerIndex) => {
    layer.classList.toggle("active", layerIndex === index);
  });
  storySteps.forEach((step, stepIndex) => {
    step.classList.toggle("active", stepIndex === index);
  });
}

function updateScrollEffects() {
  const scrollY = window.scrollY || document.documentElement.scrollTop;
  const maxScroll = Math.max(1, document.documentElement.scrollHeight - window.innerHeight);
  const progress = Math.min(1, Math.max(0, scrollY / maxScroll));

  document.documentElement.style.setProperty("--scroll-progress", String(progress));

  if (siteHeader) {
    siteHeader.classList.toggle("is-scrolled", scrollY > 24);
  }

  if (heroMedia) {
    const heroOffset = Math.min(60, scrollY * 0.08);
    const heroScale = Math.max(1.01, 1.045 - scrollY * 0.00003);
    document.documentElement.style.setProperty("--hero-y", `${heroOffset}px`);
    document.documentElement.style.setProperty("--hero-scale", heroScale.toFixed(3));
  }

  if (storySteps.length && storyLayers.length) {
    let activeIndex = 0;
    let closestDistance = Number.POSITIVE_INFINITY;
    storySteps.forEach((step, index) => {
      const rect = step.getBoundingClientRect();
      const distance = Math.abs(rect.top + rect.height / 2 - window.innerHeight / 2);
      if (distance < closestDistance) {
        closestDistance = distance;
        activeIndex = index;
      }
    });
    setStoryStep(activeIndex);
  }

  ticking = false;
}

function requestScrollUpdate() {
  if (ticking) return;
  ticking = true;
  window.requestAnimationFrame(updateScrollEffects);
}

window.addEventListener("scroll", requestScrollUpdate, { passive: true });
window.addEventListener("resize", requestScrollUpdate);

updateScrollEffects();
setLanguage("en");
