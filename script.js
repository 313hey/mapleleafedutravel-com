const languageButtons = document.querySelectorAll(".lang-btn");
const menuToggle = document.querySelector(".menu-toggle");
const navMenu = document.querySelector("#navMenu");
const form = document.querySelector("#contactForm");
const formMessage = document.querySelector("#formMessage");
const modal = document.querySelector("#policyModal");
const modalDialog = modal.querySelector(".modal-dialog");
const modalTitle = document.querySelector("#modalTitle");
const modalBody = document.querySelector("#modalBody");
let activeLanguage = "en";

function setLanguage(language) {
  activeLanguage = language;
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key]) {
      element.textContent = translations[language][key];
    }
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.lang === language;
    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  if (formMessage.textContent.trim()) {
    formMessage.textContent = translations[language].formThanks;
  }
}

function closeMobileMenu() {
  navMenu.classList.remove("open");
  menuToggle.setAttribute("aria-expanded", "false");
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.lang));
});

menuToggle.addEventListener("click", () => {
  const isOpen = navMenu.classList.toggle("open");
  menuToggle.setAttribute("aria-expanded", String(isOpen));
});

document.querySelectorAll(".nav-links a, .nav-tools a").forEach((link) => {
  link.addEventListener("click", closeMobileMenu);
});

form.addEventListener("submit", (event) => {
  event.preventDefault();
  formMessage.textContent = translations[activeLanguage].formThanks;
  form.reset();
});

function openModal(type) {
  const titleKey = type === "terms" ? "termsTitle" : "privacyTitle";
  const bodyKey = type === "terms" ? "termsBody" : "privacyBody";
  modalTitle.textContent = translations[activeLanguage][titleKey];
  modalBody.innerHTML = translations[activeLanguage][bodyKey];
  modal.classList.add("active");
  modal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
  modalDialog.focus();
}

function closeModal() {
  modal.classList.remove("active");
  modal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
}

document.querySelectorAll("[data-modal]").forEach((button) => {
  button.addEventListener("click", () => openModal(button.dataset.modal));
});

document.querySelectorAll("[data-close-modal]").forEach((element) => {
  element.addEventListener("click", closeModal);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape" && modal.classList.contains("active")) {
    closeModal();
  }
});

const revealElements = document.querySelectorAll(".reveal");

if ("IntersectionObserver" in window) {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12 });

  revealElements.forEach((element) => observer.observe(element));
} else {
  revealElements.forEach((element) => element.classList.add("visible"));
}

setLanguage("en");
